let japanesePokemonMapPromise = null;


function normalizePokemonName(name) {
  return String(name || "")
    .normalize("NFKC")
    .trim();
}


function loadJapanesePokemonMap() {

  if (japanesePokemonMapPromise) {
    return japanesePokemonMapPromise;
  }


  japanesePokemonMapPromise = fetch(
    "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv"
  )
    .then(response => response.text())
    .then(text => {

      const map = {};

      const lines = text.split(/\r?\n/);


      for (const line of lines) {

        const parts = line.split(",");

        const speciesId = parts[0];
        const languageId = parts[1];
        const name = parts[2];


        if (
          (languageId === "1" || languageId === "11") &&
          name
        ) {

          map[
            normalizePokemonName(name)
          ] = speciesId;
        }
      }


      return map;
    });


  return japanesePokemonMapPromise;
}


function getBasePokemonName(name) {

  return normalizePokemonName(name)
    .replace(/（.*?）/g, "")
    .replace(/\(.*?\)/g, "")
    .trim();
}


async function getPokemonImage(name) {

  try {

    const normalizedName =
      normalizePokemonName(name);

    let endpoint = "";


    // =========================
    // 特殊フォーム
    // =========================

    if (
      pokemonFormAliases[
        normalizedName
      ]
    ) {

      endpoint =
        "https://pokeapi.co/api/v2/pokemon/" +
        pokemonFormAliases[
          normalizedName
        ];

    } else {

      // =========================
      // 通常ポケモン
      // =========================

      const japaneseMap =
        await loadJapanesePokemonMap();


      let speciesId =
        japaneseMap[
          normalizedName
        ];


      // フォルム名が未登録だった場合の保険
      if (!speciesId) {

        const baseName =
          getBasePokemonName(
            normalizedName
          );


        speciesId =
          japaneseMap[
            baseName
          ];
      }


      if (!speciesId) {

        console.warn(
          "ポケモンIDが見つかりません:",
          name
        );

        return "";
      }


      endpoint =
        "https://pokeapi.co/api/v2/pokemon/" +
        speciesId;
    }


    const response =
      await fetch(endpoint);


    if (!response.ok) {

      console.warn(
        "PokéAPI取得失敗:",
        name,
        endpoint
      );

      return "";
    }


    const data =
      await response.json();


    // =========================
    // ドット絵だけ使う
    // =========================

    // ドット絵のみ使用
const defaultSprite =
  data.sprites?.front_default;

return defaultSprite || "";


  } catch (error) {

    console.error(
      "画像取得エラー:",
      name,
      error
    );

    return "";
  }
}
