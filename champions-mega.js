function getRuleRank(rule) {

  if (rule === "レギュレーション M-A") {
    return 1;
  }

  if (rule === "レギュレーション M-B") {
    return 2;
  }

  if (rule === "レギュレーション M-C") {
    return 3;
  }

  return 0;
}


function getUnlockRank(unlock) {

  if (unlock === "A") return 1;
  if (unlock === "B") return 2;
  if (unlock === "C") return 3;

  return 99;
}


function getMegaOptions(pokemonName, rule) {

  const options =
    championsMegaData[pokemonName] || [];

  const ruleRank =
    getRuleRank(rule);

  return options.filter(option => {
    return getUnlockRank(option.unlock) <= ruleRank;
  });
}
